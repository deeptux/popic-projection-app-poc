/**
 * Writes src/environments/environment.production.ts from POPIC_API_BASE_URL (Vercel / CI).
 * Default keeps local production builds pointing at http://127.0.0.1:8000.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const outFile = path.join(root, 'src', 'environments', 'environment.production.ts');

const onVercel = process.env.VERCEL === '1';
let base = process.env.POPIC_API_BASE_URL?.trim();
if (!base) {
  if (onVercel) {
    console.error(
      'POPIC_API_BASE_URL is missing. Add it in Vercel → Settings → Environment Variables for Production (and Preview if needed), enable it for builds, then redeploy. It must be your Cloud Run HTTPS URL (…run.app), not your *.vercel.app site URL.'
    );
    process.exit(1);
  }
  base = 'http://127.0.0.1:8000';
}
while (base.endsWith('/')) {
  base = base.slice(0, -1);
}
if (onVercel && base.includes('.vercel.app')) {
  console.error(
    'POPIC_API_BASE_URL must point to the Cloud Run API host (e.g. …run.app), not your *.vercel.app site. Fix the variable and redeploy.'
  );
  process.exit(1);
}
const escaped = base.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const content = `// Generated by scripts/set-api-base.mjs — do not edit by hand in CI\nexport const environment = {\n  production: true,\n  apiBase: '${escaped}',\n};\n`;

fs.writeFileSync(outFile, content, 'utf8');
